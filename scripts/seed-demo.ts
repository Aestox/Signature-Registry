async function seedDemoRecords() {
  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) throw new Error("DATABASE_URL is required.");
  const hostname = new URL(databaseUrl).hostname;
  if (!["localhost", "127.0.0.1", "::1"].includes(hostname)) {
    throw new Error("Demo seed is restricted to a local PostgreSQL database.");
  }

  const demoNotes = demoRecords.map((record) => record.notes);
  const existingRecords = await db
    .select({ notes: registryRecords.notes })
    .from(registryRecords)
    .where(inArray(registryRecords.notes, demoNotes));
  const existingNotes = new Set(existingRecords.map((record) => record.notes));
  const missingRecords = demoRecords.filter(
    (record) => !existingNotes.has(record.notes),
  );

  if (missingRecords.length) {
    await db.insert(registryRecords).values(missingRecords);
  }

  console.log(
    `Demo data ready: ${demoRecords.length} records, ${missingRecords.length} added.`,
  );
}

async function main() {
  try {
    await seedDemoRecords();
  } finally {
    await client.end({ timeout: 5 });
  }
}

void main().catch((error: unknown) => {
  console.error(error instanceof Error ? error.message : "Demo seed failed.");
  process.exitCode = 1;
});
